import type { AuditAction, AuditDetail } from './audit.ts'

/**
 * How 审计记录 may show each field of each action's strict detail (`audit-view.ts`): `show`, the value as written (an
 * enum, a boolean, a count, a list of enum words); `short`, a public id or a hash of public facts, as its first 8
 * characters (an id is resolved to its name where the reader may see it); `hidden`, never, because it is derived from
 * secret material (a relay's registration key, a key's hash) or says nothing a person can use. Typed over every field of
 * every action, so a new field is not shown until someone decides how: the build fails until it is marked.
 */
export type AuditFieldView = 'show' | 'short' | 'hidden'
type Keys<T> = T extends unknown ? keyof T : never
export type AuditFieldTable = { readonly [A in AuditAction]: { readonly [K in Keys<AuditDetail<A>>]-?: AuditFieldView } }

