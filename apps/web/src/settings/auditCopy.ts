/** The Host keeps the audit label in Chinese. The page selects a translation by the action key. */
export function auditActionLabel({ action, label }: Pick<AuditEntry, 'action' | 'label'>): string {
  if (currentLocale() === 'zh-CN') return label
  return Object.hasOwn(actionLabels, action) ? actionLabels[action]! : action
}
